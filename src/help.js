/** 只在浏览器里才有意义的条目（APP 里内核与地址都是固定的，说了反而误导） */
const WEB_ONLY = ['<b>浏览器要求</b>', '<b>调试地址别混</b>'];

/**
 * 把文案渲染进弹窗容器（没有 DOM 时为空操作）
 * @param {boolean} [opts.native] 跑在 Capacitor 壳里时隐掉浏览器专属条目
 */
export function renderHelp(bodyEl, opts = {}) {
  if (!bodyEl) return;
  const skip = opts.native ? WEB_ONLY : [];
  const sections = HELP_SECTIONS
    .map((sec) => ({
      title: sec.title,
      items: sec.items.filter((t) => !skip.some((p) => t.indexOf(p) === 0)),
    }))
    .filter((sec) => sec.items.length > 0);
  bodyEl.innerHTML = sections.map((sec) => (
    `<section class="help-sec">
       <h3>${sec.title}</h3>
       <ul>${sec.items.map((t) => `<li>${t}</li>`).join('')}</ul>
     </section>`
  )).join('');
}
